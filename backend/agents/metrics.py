from prometheus_client import Counter, Histogram, Gauge

# Agent call counters
agent_calls = Counter(
    'agent_calls_total',
    'Total number of agent calls',
    ['agent_name', 'ticker']
)

# Agent latency
agent_latency = Histogram(
    'agent_duration_seconds',
    'Time spent running each agent',
    ['agent_name']
)

# Mistral / Provider API errors
mistral_errors = Counter(
    'mistral_errors_total',
    'Total LLM API errors',
    ['agent_name']
)

# Cache hits
cache_hits = Counter(
    'cache_hits_total',
    'Total cache hits',
    ['ticker']
)

# Active analyses
active_analyses = Gauge(
    'active_analyses',
    'Number of analyses currently running'
)

# === LLM TOKEN USAGE METRICS (Prometheus & Grafana) ===
llm_prompt_tokens_total = Counter(
    'llm_prompt_tokens_total',
    'Total prompt (input) tokens processed by LLM',
    ['agent_name', 'model', 'ticker']
)

llm_completion_tokens_total = Counter(
    'llm_completion_tokens_total',
    'Total completion (output) tokens generated by LLM',
    ['agent_name', 'model', 'ticker']
)

llm_total_tokens_total = Counter(
    'llm_total_tokens_total',
    'Total combined tokens consumed across all LLM operations',
    ['agent_name', 'model', 'ticker']
)

llm_duration_seconds = Histogram(
    'llm_duration_seconds',
    'Latency of individual LLM completions in seconds',
    ['agent_name', 'model']
)

# === SEMANTIC EVALUATION & GUARDRAIL METRICS ===
footprint_faithfulness_score = Gauge(
    'footprint_faithfulness_score',
    'Faithfulness and grounding score of agent output (0.0 to 1.0)',
    ['ticker']
)

footprint_evaluation_score = Gauge(
    'footprint_evaluation_score',
    'Overall semantic quality score of corporate footprint (0.0 to 1.0)',
    ['ticker', 'grade']
)

footprint_hallucinations_detected_total = Counter(
    'footprint_hallucinations_detected_total',
    'Total hallucinations flagged and intercepted by guardrails',
    ['ticker']
)

# === MULTI-AGENT OBSERVABILITY & EVALUATION METRICS ===
agent_faithfulness_score = Gauge(
    'agent_faithfulness_score',
    'Factual faithfulness and grounding score of agent output (0.0 to 1.0)',
    ['agent_name', 'ticker']
)

agent_evaluation_score = Gauge(
    'agent_evaluation_score',
    'Overall semantic quality score of agent output (0.0 to 1.0)',
    ['agent_name', 'ticker', 'grade']
)

agent_hallucinations_detected_total = Counter(
    'agent_hallucinations_detected_total',
    'Total hallucinations caught and intercepted across all agents',
    ['agent_name', 'ticker']
)